CHAT_SYSTEM = """Ты — личный аналитик читателя. Отвечаешь на его вопросы по-русски, коротко и по делу, с учётом последней сводки (ниже). Если вопрос про новость из сводки — объясни подробнее: контекст, механизм, последствия, что смотреть дальше.

О читателе:
{profile}

Веб-поиск используй, только если в сводке не хватает фактов (не больше {search_limit} запросов). Ничего не выдумывай; если не знаешь — так и скажи. Указывай источники ссылками.

Формат — Telegram HTML: только <b> <i> <u> <s> <a href="https://…"> <code> <blockquote>, никакого Markdown. Обычно 600–1500 знаков.

Сейчас: {now}.

Последняя сводка:
{digest}"""


def thresholds_text(cfg) -> str:
    parts = [f"{m.name} {m.alert_pct:g}%" for m in cfg.markets if m.alert_pct]
    return ", ".join(parts)


def digest_system(cfg, kind: str, now_local: datetime, search_limit: int, search_on: bool) -> str:
    date_ru = ru_date(now_local)
    structure = (MORNING_STRUCTURE if kind == "morning" else EVENING_STRUCTURE).format(date_ru=date_ru)
    length = (f"{cfg.get('digest.morning_chars', '2500–4000')} знаков" if kind == "morning"
              else f"{cfg.get('digest.evening_chars', 'до 4500')} знаков")
    rubrics = "\n".join(f"{r['title']}" for r in cfg.rubrics)
    return DIGEST_SYSTEM.format(
        kind_name="утреннюю" if kind == "morning" else "вечернюю",
        date_ru=date_ru,
        profile=cfg.profile,
        items_min=cfg.get("digest.items_min", 12),
        items_max=cfg.get("digest.items_max", 20),
        search_limit=search_limit,
        search_note="" if search_on else " Сейчас поиск недоступен — работай только с входом.",
        thresholds=thresholds_text(cfg),
        length=length,
        structure=structure,
        rubrics=rubrics,
    )
